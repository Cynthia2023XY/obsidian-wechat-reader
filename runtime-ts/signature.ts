/** 对 UTF-8 字节排序并双重摘要，保持一期协议的签名结果 */
export function signature(values: string[]): string {
    // 每个参数按协议逐字节置换，盐值不进行置换。
    const parts = values.map(value => Buffer.from([...Buffer.from(value, 'utf8')].map(byte => SBOX[byte])));
    parts.push(Buffer.from('5a6f1'));
    parts.sort(Buffer.compare);
    // 环形偏移基于完整字节异或值。
    const rotate = (bytes: Buffer): Buffer => {
        // 每轮偏移最多十字节，但仍以输入长度取模。
        const shift = bytes.reduce((value, byte) => value ^ byte, 0) % 11;
        // 新缓冲区避免修改前一轮排序结果。
        const output = Buffer.alloc(bytes.length);
        for (let index = 0; index < bytes.length; index++)
            output[(index + shift) % bytes.length] = bytes[index];
        return output;
    };
    // 第一轮摘要以 ASCII 十六进制字符串参与第二轮。
    const first = createHash('sha256').update(rotate(Buffer.concat(parts))).digest('hex');
    return createHash('sha256').update(rotate(Buffer.from(first, 'ascii'))).digest('hex');
}
